package Day_14;

public class PrettyPrinting {
    public static void main(String[] args) {
        float a=453.764575f;
        System.out.printf("formatted no is %.2f",a);
        System.out.println();
        double pi=Math.PI;
        System.out.printf("formatted pi= %.4f",pi);
        System.out.println(); 
        System.out.printf("My name is  %s and i am %s","Rohit","Pro Player");
       /*There are many format specifiers we can use. Here are some common ones:

%c - Character
%d - Decimal number (base 10)
%e - Exponential floating-point number
%f - Floating-point number
%i - Integer (base 10)
%o - Octal number (base 8)
%s - String
%u - Unsigned decimal (integer) number
%x - Hexadecimal number (base 16)
%t - Date/time
%n - Newline 

different place holders list for like upper ones
*/
    }
}
